-- 06_roles_grants.sql: object privileges for the five Talos users.
-- The users themselves are created (or have their passwords reset) by talos init in
-- Python before this file runs, because CREATE USER takes the password as a quoted
-- identifier. Schema-level grants also cover tables created later in that schema.
--
-- Invariant: no user holds UPDATE or DELETE on any RAW_*, GRAPH or GOV table.
-- The only UPDATE in the system is on RESOLVE.W_COMPONENT_RUN (transient, not evidence).

GRANT CREATE SESSION TO TALOS_LOADER;
GRANT CREATE SESSION TO TALOS_PIPELINE;
GRANT CREATE SESSION TO TALOS_APPROVER;
GRANT CREATE SESSION TO TALOS_READER;
GRANT CREATE SESSION TO TALOS_EVAL;

-- TALOS_LOADER: talos load (append raw snapshots, truth, initial policy).
GRANT SELECT, INSERT ON RAW_LOS TO TALOS_LOADER;
GRANT SELECT, INSERT ON RAW_TREASURY TO TALOS_LOADER;
GRANT SELECT, INSERT ON RAW_GUARANTEE TO TALOS_LOADER;
GRANT SELECT, INSERT ON RAW_COLLATERAL TO TALOS_LOADER;
GRANT SELECT, INSERT ON RAW_REGISTRY TO TALOS_LOADER;
GRANT SELECT, INSERT, DELETE ON TRUTH TO TALOS_LOADER;
GRANT SELECT, INSERT, DELETE ON STAGE.PINCODE_DISTRICT TO TALOS_LOADER;
GRANT SELECT, INSERT ON GOV.POLICY_EVENT TO TALOS_LOADER;

-- TALOS_PIPELINE: talos match / publish / replay and the judge.
GRANT SELECT ON RAW_LOS TO TALOS_PIPELINE;
GRANT SELECT ON RAW_TREASURY TO TALOS_PIPELINE;
GRANT SELECT ON RAW_GUARANTEE TO TALOS_PIPELINE;
GRANT SELECT ON RAW_COLLATERAL TO TALOS_PIPELINE;
GRANT SELECT ON RAW_REGISTRY TO TALOS_PIPELINE;
GRANT SELECT ON GRAPH TO TALOS_PIPELINE;
GRANT SELECT ON GOV TO TALOS_PIPELINE;
GRANT SELECT, INSERT, DELETE ON STAGE TO TALOS_PIPELINE;
GRANT SELECT, INSERT, DELETE ON RESOLVE TO TALOS_PIPELINE;
GRANT UPDATE ON RESOLVE.W_COMPONENT_RUN TO TALOS_PIPELINE;
GRANT INSERT ON GOV.PROPOSAL TO TALOS_PIPELINE;
GRANT INSERT ON GOV.REPORT_RUN TO TALOS_PIPELINE;
GRANT INSERT ON GOV.RUN_MEMBERSHIP TO TALOS_PIPELINE;
GRANT INSERT ON GOV.RUN_OUTPUT TO TALOS_PIPELINE;
GRANT INSERT ON GOV.RUN_REPORTED TO TALOS_PIPELINE;
GRANT INSERT ON GOV.PIPELINE_TIMING TO TALOS_PIPELINE;

-- TALOS_APPROVER: decision routes only (orchestrator/decide.py).
GRANT SELECT ON STAGE TO TALOS_APPROVER;
GRANT SELECT ON RESOLVE TO TALOS_APPROVER;
GRANT SELECT ON GRAPH TO TALOS_APPROVER;
GRANT SELECT ON GOV TO TALOS_APPROVER;
GRANT SELECT ON RAW_REGISTRY TO TALOS_APPROVER;
GRANT INSERT ON GRAPH.LINK_EVENT TO TALOS_APPROVER;
GRANT INSERT ON GRAPH.OWNERSHIP_EVENT TO TALOS_APPROVER;
GRANT INSERT ON GRAPH.RULING_EVENT TO TALOS_APPROVER;
GRANT INSERT ON GRAPH.ENTITY TO TALOS_APPROVER;
GRANT INSERT ON GOV.DECISION_LOG TO TALOS_APPROVER;
GRANT INSERT ON GOV.DECISION_COVERS TO TALOS_APPROVER;
GRANT INSERT ON GOV.POLICY_EVENT TO TALOS_APPROVER;

-- TALOS_READER: web screens and the Exasol MCP server. REPORT views run with the
-- owner's rights, so no grant on a base table is needed.
GRANT SELECT ON REPORT TO TALOS_READER;

-- TALOS_EVAL: talos eval reads everything, including TRUTH.
GRANT SELECT ON RAW_LOS TO TALOS_EVAL;
GRANT SELECT ON RAW_TREASURY TO TALOS_EVAL;
GRANT SELECT ON RAW_GUARANTEE TO TALOS_EVAL;
GRANT SELECT ON RAW_COLLATERAL TO TALOS_EVAL;
GRANT SELECT ON RAW_REGISTRY TO TALOS_EVAL;
GRANT SELECT ON STAGE TO TALOS_EVAL;
GRANT SELECT ON RESOLVE TO TALOS_EVAL;
GRANT SELECT ON GRAPH TO TALOS_EVAL;
GRANT SELECT ON GOV TO TALOS_EVAL;
GRANT SELECT ON REPORT TO TALOS_EVAL;
GRANT SELECT ON TRUTH TO TALOS_EVAL;
